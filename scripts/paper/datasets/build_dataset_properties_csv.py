"""Build a dataset-properties CSV from selected eval stats JSON files.

Input files are one or more `*_eval_stats.json` artifacts generated by:
    python -m scripts.benchmark.v2.cli eval-source

Output columns:
    dataset, # VP, # ASN, # Target, # Target Cluster, % Colocated VPs

Notes:
- `# VP`, `# Target`, and `# Target Cluster` are read from each stats JSON.
- `% Colocated VPs` uses
  `target_clustering.closest_vp_within_radius_share * 100`.
- `# ASN` is computed from the source CSV referenced by each stats JSON's `csv`
  field. The script prefers unique `target_asn` values; if missing, it falls
  back to unique `vp_asn` values.

Example:
    /home/sw6456/geomodel/cbg-framework/.venv/bin/python \
      -m scripts.paper.datasets.build_dataset_properties_csv \
      --stats-jsons scripts/paper/datasets/outputs/*_eval_stats.json \
      --out-csv scripts/paper/datasets/outputs/dataset_properties.csv
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd


def _dataset_name_from_stats_path(stats_json: Path) -> str:
    stem = stats_json.stem
    suffix = "_eval_stats"
    if stem.endswith(suffix):
        return stem[: -len(suffix)]
    return stem


def _resolve_source_csv(stats_json: Path, csv_field: str) -> Path:
    p = Path(csv_field)
    if p.is_absolute() and p.exists():
        return p

    candidates = [
        Path.cwd() / p,
        stats_json.parent / p,
    ]
    for cand in candidates:
        if cand.exists():
            return cand

    raise FileNotFoundError(
        f"could not resolve source CSV '{csv_field}' from {stats_json}"
    )


def _count_unique_asn(source_csv: Path) -> int:
    header = pd.read_csv(source_csv, nrows=0)
    cols = set(header.columns)

    if "target_asn" in cols:
        asn = pd.read_csv(source_csv, usecols=["target_asn"])["target_asn"]
    elif "vp_asn" in cols:
        asn = pd.read_csv(source_csv, usecols=["vp_asn"])["vp_asn"]
    else:
        raise ValueError(
            f"{source_csv} missing ASN columns. Expected 'target_asn' or 'vp_asn'."
        )

    asn = asn.dropna()
    return int(asn.nunique())


def _build_row(stats_json: Path) -> dict:
    data = json.loads(stats_json.read_text())

    csv_field = data.get("csv")
    if not isinstance(csv_field, str) or not csv_field.strip():
        raise ValueError(f"{stats_json} missing non-empty 'csv' field")

    target_clustering = data.get("target_clustering")
    if not isinstance(target_clustering, dict):
        raise ValueError(f"{stats_json} missing 'target_clustering' mapping")

    colocated_share = target_clustering.get("closest_vp_within_radius_share")
    if colocated_share is None:
        raise ValueError(
            f"{stats_json} missing target_clustering.closest_vp_within_radius_share"
        )

    source_csv = _resolve_source_csv(stats_json, csv_field)

    return {
        "dataset": _dataset_name_from_stats_path(stats_json),
        "# VP": int(data["n_vps"]),
        "# ASN": _count_unique_asn(source_csv),
        "# Target": int(data["n_targets"]),
        "# Target Cluster": int(target_clustering["n_clusters"]),
        "% Colocated VPs": float(colocated_share) * 100.0,
    }


def build_dataset_properties(stats_jsons: list[Path]) -> pd.DataFrame:
    rows = [_build_row(path) for path in stats_jsons]
    return pd.DataFrame(
        rows,
        columns=[
            "dataset",
            "# VP",
            "# ASN",
            "# Target",
            "# Target Cluster",
            "% Colocated VPs",
        ],
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--stats-jsons",
        type=Path,
        nargs="+",
        required=True,
        help="List of selected eval stats JSON files.",
    )
    parser.add_argument(
        "--out-csv",
        type=Path,
        required=True,
        help="Output CSV path for dataset properties.",
    )
    parser.add_argument(
        "--percent-decimals",
        type=int,
        default=1,
        help="Decimal places for '% Colocated VPs'.",
    )
    args = parser.parse_args()

    table = build_dataset_properties(args.stats_jsons)
    table["% Colocated VPs"] = table["% Colocated VPs"].round(args.percent_decimals)

    args.out_csv.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(args.out_csv, index=False)
    print(f"Saved {args.out_csv} ({len(table)} rows)")


if __name__ == "__main__":
    main()
